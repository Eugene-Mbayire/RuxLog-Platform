// ==========================================================
// RuxLog Platform — PDF reports
//
// Shared by Analytics, Petty Cash and the driver dashboard, so they
// all produce an identical looking report. Built with jsPDF +
// autotable, loaded from a CDN on any page that includes this file —
// generating a real PDF in the browser isn't something plain JS can
// do on its own.
//
// Rows must already be newest-first: this renders them and then
// hard-caps the result at maxPages, dropping anything that would have
// flowed further, so the most recent activity is always what's kept.
// Analytics uses the 2-page default; the Petty Cash report asks for 1.
// ==========================================================

function newPdfDoc() {
  const { jsPDF } = window.jspdf;
  return new jsPDF({ orientation: "landscape" });
}

// Header drawn at the top of the current page.
function drawPdfHeader(doc, title) {
  // "Generated by RuxLog" with the brand word picked out in gold, the
  // same way it's highlighted on the generated schedule. jsPDF has no
  // rich text, so it's drawn as two pieces and the second is placed
  // at the measured width of the first.
  doc.setFontSize(11);
  doc.setFont(undefined, "normal");
  doc.setTextColor(120);
  const prefix = "Generated by ";
  doc.text(prefix, 14, 13);

  doc.setFont(undefined, "bold");
  doc.setTextColor(242, 184, 75); // #f2b84b, the schedule's brand gold
  doc.text("RuxLog", 14 + doc.getTextWidth(prefix), 13);

  doc.setFont(undefined, "bold");
  doc.setTextColor(30, 58, 95); // --ruxlog-primary
  doc.setFontSize(14);
  doc.text(title, 14, 21);

  doc.setFont(undefined, "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(`${new Date().toLocaleString()} — most recent first`, 14, 27);
}

function drawPdfTable(doc, headers, rows) {
  doc.autoTable({
    head: [headers],
    body: rows,
    startY: 32,
    styles: { fontSize: 8 },
    headStyles: { fillColor: [30, 58, 95] }, // matches --ruxlog-primary
  });
}

function buildPdf(title, headers, rows, maxPages = 2) {
  const doc = newPdfDoc();
  drawPdfHeader(doc, title);
  drawPdfTable(doc, headers, rows);

  const totalPages = doc.internal.getNumberOfPages();
  for (let page = totalPages; page > maxPages; page--) {
    doc.deletePage(page);
  }

  return doc;
}

function downloadPdf(filename, title, headers, rows, maxPages = 2) {
  buildPdf(title, headers, rows, maxPages).save(filename);
}

// ---------- Petty cash transactions report ----------
// One report covering every vehicle's pool, used by the Analytics
// download and the driver dashboard's share button so both hand out
// the same document. Each vehicle gets exactly one page of its own,
// in make_model order (Tang, then Titanium), keeping the newest rows
// that fit on that page.
//
// Balance is the vehicle's pool balance right after that row, following
// the same rules as the petty_cash_balance view: a withdrawal always
// comes out, a refill only counts once it's approved, and a
// soft-deleted row still counts even though it's left out of the list.
//
// transactions must embed profiles!user_id(full_name).
function pettyCashReport(transactions, vehicles) {
  const oldestFirst = transactions
    .slice()
    .sort((a, b) => new Date(a.created_at) - new Date(b.created_at));

  const balances = {};
  const rowsByVehicle = {};
  oldestFirst.forEach((t) => {
    const amount = Number(t.amount);
    let balance = balances[t.vehicle_id] || 0;
    if (t.type === "withdrawal") balance -= amount;
    else if (t.status === "approved") balance += amount;
    balances[t.vehicle_id] = balance;

    if (t.deleted_at) return;

    (rowsByVehicle[t.vehicle_id] = rowsByVehicle[t.vehicle_id] || []).push([
      new Date(t.created_at).toLocaleString(),
      t.type === "refill" && t.status !== "approved" ? "refill (pending)" : t.type,
      amount,
      t.profiles ? t.profiles.full_name : "Unknown",
      t.reason || "",
      balance,
    ]);
  });

  return {
    headers: ["Date", "Type", "Amount (RWF)", "Name", "Reason", "Balance (RWF)"],
    sections: vehicles
      .slice()
      .sort((a, b) => a.make_model.localeCompare(b.make_model))
      .map((v) => ({
        title: `Petty Cash Transactions — ${v.make_model} (${v.plate_number})`,
        rows: (rowsByVehicle[v.id] || []).reverse(),
      })),
  };
}

function hasPettyCashRows(report) {
  return report.sections.some((s) => s.rows.length > 0);
}

function buildPettyCashPdf(report) {
  const doc = newPdfDoc();

  report.sections.forEach((section, index) => {
    if (index > 0) doc.addPage();
    const firstPage = doc.internal.getNumberOfPages();

    drawPdfHeader(doc, section.title);
    const rows = section.rows.length
      ? section.rows
      : [[{ content: "No transactions yet.", colSpan: report.headers.length }]];
    drawPdfTable(doc, report.headers, rows);

    // Anything that flowed past this vehicle's one page is the oldest
    // activity — dropped so the next vehicle starts on the next page.
    for (let page = doc.internal.getNumberOfPages(); page > firstPage; page--) {
      doc.deletePage(page);
    }
  });

  return doc;
}
